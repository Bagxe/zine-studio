// Generates src/lib/zineArrangerData.ts from scripts/templates.json + ground-truth.json
// (gridType per variant is taken from the ground-truth sheet classes).
import { readFileSync, writeFileSync } from 'node:fs'

const ROOT = 'C:/Users/Gabriel/Documents/kimi/workspace/zine-studio'
const templates = JSON.parse(readFileSync(`${ROOT}/scripts/templates.json`, 'utf8'))
const truth = JSON.parse(readFileSync(`${ROOT}/scripts/ground-truth.json`, 'utf8'))

for (const key of Object.keys(templates)) {
  const t = templates[key]
  const g = truth[key]
  if (!g) {
    // half has no 'top' variants; ensure key exists for all
    console.error(`missing ground truth for ${key}`)
    process.exit(1)
  }
  const first = Object.values(g)[0]
  let gridType = first.sheets[0].sheetClass.split(' ')[0]
  // Quarter single-sided omits the grid class in the reference, falling back to
  // the default .zine-sheet grid ("tl tr" / "bl br") — identical to qtr-side.
  if (gridType === 'guide-margins' || gridType === '') gridType = 'qtr-side'
  t.grid = gridType
  if (t.k == null) t.k = t.loopBound / 2
}


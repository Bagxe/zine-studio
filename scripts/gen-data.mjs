export type EdgeLetter = 't' | 'b' | 'l' | 'r'
export type PageBase = 's' | 'e' | 'm' | 'n'

export interface CellTemplate {
  /** Grid area name (tl/tr/.../gRC). */
  area: string
  base: PageBase
  offset: number
  /** Quarter "two copies" mode: second copy of the same page. */
  copy: boolean
  /** Rotate cell contents 180 degrees. */
  rotate: boolean
  /** Cut guides (solid when Center guides on). */
  cuts: EdgeLetter[]
  /** Fold guides (dotted). */
  folds: EdgeLetter[]
  /** Alternate treatment when this cell holds the back cover of a top-fold zine and flipBackCover is off. */
  bcAlt?: { rotate: boolean; cuts: EdgeLetter[]; folds: EdgeLetter[] }
}

export interface SheetTemplate {
  sheetInIter: number
  cells: CellTemplate[]
}

export interface VariantTemplate {
  /** Pages per sheet of paper (front+back for duplex). */
  loopBound: number
  /** Step of the s counter per sheet pair. */
  k: number
  /** Whether the m/n middle variables are used (quarter regular duplex). */
  useMN: boolean
  sheetsPerIter: number
  /** CSS grid class from the reference (half-por, qtr-side, eig-lnd, twlv-por, ...). */
  grid: string
  sheets: SheetTemplate[]
}

